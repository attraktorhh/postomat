import { Tabs } from '@heroui/react';
import type { PostView } from '../server/views.server';

/** Read-only previews of every channel ("Alle Kanäle" + one tab per channel). */
export function ChannelPreviews({ view }: { view: PostView }) {
  const p = view.previews;
  const banner4x5 = `/banner/${view.post.id}/4x5`;
  const banner16x9 = `/banner/${view.post.id}/16x9`;
  const ig = p.instagram && (
    <div className="overflow-hidden rounded-lg border border-[var(--border)]">
      <div className="px-3 py-2 text-sm font-semibold">attraktor_org</div>
      {view.hasBanner && (
        <img src={banner4x5} alt="Banner 4:5" className="block w-full" />
      )}
      <div className="pm-pre p-3 text-sm">{p.instagram}</div>
    </div>
  );
  const meetup = p.meetup && (
    <div className="overflow-hidden rounded-lg border border-[var(--border)]">
      {view.hasBanner && (
        <img src={banner16x9} alt="Banner 16:9" className="block w-full" />
      )}
      <div className="grid gap-1 p-3 text-sm">
        <span className="text-xs font-semibold uppercase text-[var(--muted)]">
          {p.meetup.find((f) => f.key === 'date')?.value} ·{' '}
          {p.meetup.find((f) => f.key === 'time')?.value}
        </span>
        <b>{p.meetup.find((f) => f.key === 'title')?.value}</b>
        <span className="pm-pre">
          {p.meetup.find((f) => f.key === 'description')?.value}
        </span>
      </div>
    </div>
  );
  const website = p.website && (
    <article className="rounded-lg border border-[var(--border)] p-3 text-sm">
      {view.hasBanner && (
        <img
          src={banner16x9}
          alt="Titelbild"
          className="mb-2 block w-full rounded"
        />
      )}
      <h3 className="mb-2 text-lg font-bold">{p.website.title}</h3>
      {/* Generated by @postomat/templates, which escapes all member/editor text. */}
      <div
        className="pm-html"
        dangerouslySetInnerHTML={{ __html: p.website.html }}
      />
    </article>
  );
  const wiki = p.wiki && (
    <div className="rounded-lg border border-[var(--border)] p-3 text-sm">
      <b>{p.wiki.title}</b>
      <pre className="pm-pre mt-2 text-xs">{p.wiki.text}</pre>
    </div>
  );
  const facebook = p.facebook && (
    <div className="pm-pre rounded-lg border border-[var(--border)] p-3 text-sm">
      {p.facebook}
    </div>
  );

  const tabs = [
    { id: 'meetup', label: 'Meetup', node: meetup },
    { id: 'instagram', label: 'Instagram', node: ig },
    { id: 'website', label: 'Website', node: website },
    { id: 'wiki', label: 'Wiki', node: wiki },
    { id: 'facebook', label: 'Facebook', node: facebook },
  ].filter((t) => t.node);

  return (
    <Tabs className="w-full">
      <Tabs.ListContainer className="overflow-x-auto">
        <Tabs.List aria-label="Kanäle">
          <Tabs.Tab id="alle">
            Alle Kanäle
            <Tabs.Indicator />
          </Tabs.Tab>
          {tabs.map((t) => (
            <Tabs.Tab key={t.id} id={t.id}>
              {t.label}
              <Tabs.Indicator />
            </Tabs.Tab>
          ))}
        </Tabs.List>
      </Tabs.ListContainer>
      <Tabs.Panel id="alle" className="pt-3">
        <div className="grid gap-3 md:grid-cols-2">
          {tabs.map((t) => (
            <div key={t.id}>{t.node}</div>
          ))}
        </div>
      </Tabs.Panel>
      {tabs.map((t) => (
        <Tabs.Panel key={t.id} id={t.id} className="pt-3">
          {t.node}
        </Tabs.Panel>
      ))}
    </Tabs>
  );
}
